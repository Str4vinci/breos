"""Generate docs/getting-started/config-reference.md from the config registry.

Every top-level App key comes from ``breos.app_config.APP_CONFIG_FIELDS`` and
every nested-table key from the ``TableSpec`` that validates it, so the page
lists exactly the keys BREOS accepts, with their defaults, CLI flags and
allowed values. The descriptions are the registry's ``doc`` text; a key
without one fails the generator.

Regenerate after changing the registry:

    uv run python tools/generate_config_docs.py

CI runs this with ``--check`` and fails when the committed page is stale.
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import fields
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from breos import app_config  # noqa: E402
from breos.app_config import (  # noqa: E402
    APP_CONFIG_FIELDS,
    COSTS_TABLE,
    INDOOR_MODEL_TABLE,
    NESTED_TABLE_SPECS,
    PERIOD_TABLE,
    PV_ARRAY_TABLE,
    REFERENCE_TARIFF_TABLE,
    SMART_CHARGING_TABLE,
    TARIFF_TABLE,
    TERMINAL_VALUE_TABLE,
)
from breos.config_schema import TableSpec  # noqa: E402
from breos.economics import COST_CONFIG_KEY_TO_PARAM, CostParams  # noqa: E402

OUTPUT_PATH = REPO_ROOT / "docs" / "getting-started" / "config-reference.md"

HEADER = """\
<!-- Generated by tools/generate_config_docs.py. Do not edit by hand. -->

# Configuration key reference

Every key a {py:class}`~breos.App` config accepts, generated from the
configuration registry that validates it. A key that is not listed here is
rejected. The keys inside the `[montecarlo]` and `[sweep]` runner sections are
described on the [Monte Carlo](monte-carlo.md) and
[Run a parameter sweep](../how-to/parameter-sweep.md) pages. [Configuration](configuration.md) explains how the keys work
together; [Packaged options](options.md) lists the preset keys they accept.
"""

TOP_LEVEL_INTRO = """\
The top level of a config dict or TOML file. A CLI flag, where there is one,
is a `breos run` option that overrides the config file.
"""

# Nested tables in page order: the heading, the spec, and the introduction.
