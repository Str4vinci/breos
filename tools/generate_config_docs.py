# Keys a table's own validator requires, where adding them to the spec's
# ``required`` would change the error a missing key raises.
_ALSO_REQUIRED = {"pv_arrays": frozenset({"modules"})}
_CONDITIONALLY_REQUIRED = {
    "tariff": {
        "schedule": "exactly one of these",
        "custom_schedule": "exactly one of these",
    },
    "smart_charging": {
        "charge_periods": "`fixed_target`, `daily_persistence`",
        "discharge_periods": "unless `disabled`",
        "grid_charge_efficiency": "`fixed_target`, `daily_persistence`",
        "target_usable_fraction": "`fixed_target`",
    },
}

_COST_PARAM_DEFAULTS = {field.name: field.default for field in fields(CostParams)}


def _literal(value: Any) -> str:
    text = json.dumps(value) if isinstance(value, str) else repr(value)
    return f"`{text}`"


def _checked(where: str, text: str) -> str:
    if not text.strip():
        raise ValueError(f"{where} has no doc text; add it to the config registry")
    if "|" in text or "\n" in text:
        raise ValueError(f"{where} doc text must be one line without '|'")
    return text


def _table(header: tuple[str, ...], rows: list[tuple[str, ...]]) -> str:
    for row in rows:
        for cell in row:
            if "|" in cell or "\n" in cell:
                raise ValueError(f"Table cell {cell!r} must be one line without '|'")
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    return "\n".join(lines)


def _top_level_rows() -> list[tuple[str, ...]]:
    rows = []
    for name in sorted(APP_CONFIG_FIELDS):
        field = APP_CONFIG_FIELDS[name]
        description = _checked(name, field.doc)
        if field.cli_choices:
            description += ". One of " + ", ".join(_literal(choice) for choice in field.cli_choices)
        if field.default_doc is not None:
            default = field.default_doc
        elif field.has_default:
            default = _literal(field.default)
        else:
            raise ValueError(f"{name} has neither a default nor default_doc")
        flags = ", ".join(f"`{flag}`" for flag in field.cli_flags) or "—"
        rows.append((f"`{name}`", default, flags, description))
    return rows


def _nested_rows(spec: TableSpec, name: str) -> tuple[tuple[str, ...], list[tuple[str, ...]]]:
    undocumented = sorted(set(spec.keys) - set(spec.docs))
    stray = sorted(set(spec.docs) - set(spec.keys))
    if undocumented or stray:
        raise ValueError(f"{name}: keys without docs {undocumented}, docs without keys {stray}")
    if spec is COSTS_TABLE:
        header = ("Key", "Default", "Description")
        rows = [
            (f"`{key}`", _literal(_COST_PARAM_DEFAULTS[COST_CONFIG_KEY_TO_PARAM[key]]), _checked(key, doc))
            for key, doc in sorted(spec.docs.items())
        ]
        return header, rows
    header = ("Key", "Required", "Description")
    always_required = spec.required | _ALSO_REQUIRED.get(name, frozenset())
    conditional_required = _CONDITIONALLY_REQUIRED.get(name, {})
    required = always_required | frozenset(conditional_required)
    keys = sorted(spec.keys, key=lambda key: (key not in required, key))
    rows = [
        (
            f"`{key}`",
            conditional_required.get(key, "yes" if key in always_required else ""),
            _checked(key, spec.docs[key]),
        )
        for key in keys
    ]
    return header, rows


def generate() -> str:
    sectioned = {id(spec) for _, spec, _ in TABLES}
    specs = [
        *NESTED_TABLE_SPECS.values(),
        *(value for value in vars(app_config).values() if isinstance(value, TableSpec)),
    ]
    missing = sorted({spec.name for spec in specs if id(spec) not in sectioned})
    if missing:
        raise ValueError(f"Tables {missing} have no section; add them to TABLES")
    parts = [
        HEADER,
        f"## Top-level keys\n\n{TOP_LEVEL_INTRO}\n"
        + _table(("Key", "Default", "CLI flag", "Description"), _top_level_rows())
        + "\n",
    ]
    for name, spec, intro in TABLES:
        header, rows = _nested_rows(spec, name)
        parts.append(f"## {name}\n\n{intro}\n\n{_table(header, rows)}\n")
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if the committed page differs from the generated content.",
    )
    args = parser.parse_args(argv)

    content = generate()
    if args.check:
        committed = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.exists() else ""
        if committed != content:
            print(
                f"{OUTPUT_PATH.relative_to(REPO_ROOT)} is out of date with the config registry."
                " Run: uv run python tools/generate_config_docs.py",
                file=sys.stderr,
            )
            return 1
        print(f"{OUTPUT_PATH.relative_to(REPO_ROOT)} is up to date.")
        return 0

    OUTPUT_PATH.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
